CREATE VIEW v_stock_actual AS
SELECT
    i.id_inventario,
    ins.codigo_interno,
    ins.nombre_insumo,
    c.nombre_categoria,
    ti.nombre_tipo,
    um.abreviatura AS unidad_medida,
    a.codigo_almacen,
    a.nombre_almacen,
    a.tipo_almacen,
    i.stock_fisico,
    i.stock_reservado,
    i.stock_disponible,
    ins.stock_minimo,
    COALESCE(ps.stock_maximo, 0) AS stock_maximo,
    COALESCE(ps.stock_seguridad, 0) AS stock_seguridad,
    i.costo_promedio,
    i.valor_total_stock,
    i.estado_stock,
    i.fecha_ultima_actualizacion
FROM inventarios i
INNER JOIN insumos ins ON ins.id_insumo = i.id_insumo
INNER JOIN categorias_insumo c ON c.id_categoria = ins.id_categoria
INNER JOIN tipos_insumo ti ON ti.id_tipo_insumo = ins.id_tipo_insumo
INNER JOIN unidades_medida um ON um.id_unidad_medida = ins.id_unidad_medida
INNER JOIN almacenes a ON a.id_almacen = i.id_almacen
LEFT JOIN politicas_stock ps ON ps.id_insumo = i.id_insumo AND ps.id_almacen = i.id_almacen;

CREATE VIEW v_stock_bajo AS
SELECT *
FROM v_stock_actual
WHERE stock_disponible <= stock_minimo;

CREATE VIEW v_kardex AS
SELECT
    mi.fecha_movimiento,
    mi.numero_movimiento,
    ins.codigo_interno,
    ins.nombre_insumo,
    mi.tipo_movimiento,
    CASE WHEN mi.tipo_movimiento IN ('ENTRADA_COMPRA', 'AJUSTE_POSITIVO', 'DEVOLUCION', 'TRANSFERENCIA_ENTRADA') THEN mi.cantidad ELSE 0 END AS entrada,
    CASE WHEN mi.tipo_movimiento IN ('SALIDA_DESPACHO', 'AJUSTE_NEGATIVO', 'TRANSFERENCIA_SALIDA') THEN mi.cantidad ELSE 0 END AS salida,
    mi.costo_unitario,
    mi.motivo,
    COALESCE(ao.nombre_almacen, '-') AS almacen_origen,
    COALESCE(ad.nombre_almacen, '-') AS almacen_destino,
    u.nombre_completo AS usuario_responsable,
    mi.documento_respaldo,
    mi.observaciones
FROM movimientos_inventario mi
INNER JOIN insumos ins ON ins.id_insumo = mi.id_insumo
LEFT JOIN almacenes ao ON ao.id_almacen = mi.id_almacen_origen
LEFT JOIN almacenes ad ON ad.id_almacen = mi.id_almacen_destino
LEFT JOIN usuarios u ON u.id_usuario = mi.usuario_responsable;

CREATE VIEW v_pedidos_por_estado AS
SELECT
    estado_pedido,
    COUNT(*) AS total_pedidos
FROM pedidos
GROUP BY estado_pedido;

CREATE VIEW v_compras_por_proveedor AS
SELECT
    p.codigo_proveedor,
    p.razon_social,
    COUNT(oc.id_orden_compra) AS total_compras,
    COALESCE(SUM(oc.total_final), 0) AS monto_total_comprado
FROM proveedores p
LEFT JOIN ordenes_compra oc ON oc.id_proveedor = p.id_proveedor
GROUP BY p.codigo_proveedor, p.razon_social;

CREATE VIEW v_dashboard_resumen AS
SELECT
    (SELECT COUNT(*) FROM insumos WHERE estado = 'ACTIVO') AS total_insumos_activos,
    (SELECT COUNT(*) FROM proveedores WHERE estado = 'ACTIVO') AS total_proveedores_activos,
    (SELECT COUNT(*) FROM almacenes WHERE estado = 'ACTIVO') AS total_almacenes_activos,
    (SELECT COUNT(*) FROM usuarios WHERE estado = 'ACTIVO') AS total_usuarios_activos,
    (SELECT COUNT(*) FROM pedidos WHERE estado_pedido = 'PENDIENTE') AS pedidos_pendientes,
    (SELECT COUNT(*) FROM pedidos WHERE estado_pedido = 'APROBADO') AS pedidos_aprobados,
    (SELECT COUNT(*) FROM ordenes_compra WHERE estado_compra IN ('PENDIENTE', 'EN_PROCESO')) AS compras_en_proceso,
    (SELECT COUNT(*) FROM ordenes_compra WHERE estado_compra = 'RECIBIDA_COMPLETA') AS compras_recibidas,
    (SELECT COUNT(*) FROM v_stock_bajo) AS insumos_con_stock_bajo,
    (SELECT COALESCE(SUM(valor_total_stock), 0) FROM inventarios) AS valor_total_inventario;

