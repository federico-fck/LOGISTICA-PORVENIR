-- 4) Ver kardex completo
SELECT * FROM v_kardex ORDER BY fecha_movimiento, numero_movimiento;

-- 5) Ver pedidos con solicitante y área
SELECT
    p.numero_pedido,
    u.nombre_completo AS solicitante,
    a.nombre_area,
    p.fecha_pedido,
    p.fecha_requerida,
    p.prioridad,
    p.estado_pedido,
    p.estado_aprobacion,
    p.estado_atencion
FROM pedidos p
INNER JOIN usuarios u ON u.id_usuario = p.id_usuario_solicitante
INNER JOIN areas a ON a.id_area = p.id_area_solicitante
ORDER BY p.numero_pedido;

-- 6) Ver detalle de pedidos
SELECT
    p.numero_pedido,
    i.codigo_interno,
    i.nombre_insumo,
    pd.cantidad_solicitada,
    pd.cantidad_aprobada,
    pd.cantidad_despachada,
    pd.cantidad_pendiente
FROM pedido_detalles pd
INNER JOIN pedidos p ON p.id_pedido = pd.id_pedido
INNER JOIN insumos i ON i.id_insumo = pd.id_insumo
ORDER BY p.numero_pedido, i.nombre_insumo;

-- 7) Ver compras por proveedor
SELECT * FROM v_compras_por_proveedor ORDER BY monto_total_comprado DESC;

-- 8) Ver comprobantes registrados
SELECT
    cc.numero_comprobante,
    cc.tipo_comprobante,
    pr.razon_social AS proveedor,
    oc.numero_orden,
    cc.monto_total,
    cc.moneda,
    cc.estado_comprobante
FROM comprobantes_compra cc
INNER JOIN proveedores pr ON pr.id_proveedor = cc.id_proveedor
INNER JOIN ordenes_compra oc ON oc.id_orden_compra = cc.id_orden_compra
ORDER BY cc.numero_comprobante;

-- 9) Ver despachos realizados
SELECT
    d.numero_despacho,
    p.numero_pedido,
    a.nombre_area,
    d.persona_recibe,
    d.fecha_real_entrega,
    d.estado_despacho
FROM despachos d
INNER JOIN pedidos p ON p.id_pedido = d.id_pedido
INNER JOIN areas a ON a.id_area = d.id_area_solicitante
ORDER BY d.numero_despacho;

-- 10) Ver usuarios, roles y áreas
SELECT
    u.nombre_completo,
    u.nombre_usuario,
    u.correo,
    r.nombre_rol,
    a.nombre_area,
    u.estado
FROM usuarios u
INNER JOIN roles r ON r.id_rol = u.id_rol
INNER JOIN areas a ON a.id_area = u.id_area
ORDER BY u.id_usuario;

-- 11) Ver permisos por rol
SELECT
    r.nombre_rol,
    p.modulo,
    p.codigo_permiso,
    p.descripcion
FROM roles_permisos rp
INNER JOIN roles r ON r.id_rol = rp.id_rol
INNER JOIN permisos p ON p.id_permiso = rp.id_permiso
ORDER BY r.nombre_rol, p.modulo, p.codigo_permiso;

-- 12) Ver auditoría
SELECT
    au.fecha_hora,
    u.nombre_completo AS usuario,
    au.tipo_accion,
    au.modulo_afectado,
    au.accion_realizada,
    au.tabla_afectada,
    au.id_registro_afectado
FROM auditorias au
LEFT JOIN usuarios u ON u.id_usuario = au.id_usuario
ORDER BY au.fecha_hora DESC;

